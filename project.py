import pandas as pd

# 1. 한국전력거래소 CSV 파일 읽기 (인코딩: utf-8)
power_df = pd.read_csv('한국전력거래소_지역별 시간별 태양광 및 풍력 발전량_20251231.csv', encoding='utf-8')

# 2. 기상청 XLS 파일 읽기 (실제 구분자: tab, 인코딩: euc-kr)
weather_df = pd.read_csv('OBS_ASOS_TIM_20260922100115.xls', sep='\t', encoding='euc-kr', low_memory=False)

print("전력 데이터 불러오기 완료!")
print("기상 데이터 불러오기 완료!")

# 3. 태양광 데이터만 추출
power_solar = power_df[power_df['연료원'] == '태양광'].copy()

# 4. 날짜 및 시간(datetime) 컬럼 생성
# 거래일 + 거래시간(1~24시)을 datetime 형식으로 변환
power_solar['datetime'] = pd.to_datetime(power_solar['거래일']) + pd.to_timedelta(power_solar['거래시간'], unit='h')
weather_df['datetime'] = pd.to_datetime(weather_df['일시'])

