weather_df['지역'] = weather_df['지점명'].map(location_map)

# 6. 시간 및 지역 기준으로 데이터 병합
merged_df = pd.merge(
    power_solar[['datetime', '지역', '전력거래량(MWh)']],
    weather_df[['datetime', '지역', '지점명', '기온(°C)', '일조(hr)', '일사(MJ/m2)']],
    on=['datetime', '지역'],
    how='inner'
)

# 7. 결합 결과 파일로 저장
merged_df.to_csv('power_weather_merged.csv', index=False, encoding='utf-8-sig')

